from comp import *
m=M("Free-Coffee-Cup-on-Window-Ledge-Mockup_3/Free Coffee Cup on Window Ledge Mockup/Files/Free Coffee Cup on Window Ledge Mockup.psd",.6)
base,_=m.px('Background/Photo')
cup,ca=m.px('Cup/Cup');gm=m.mask('Cup');ca=ca*(gm if gm is not None else 1)
d,da=m.cyl('cup_slate',ca,span=1.0)
c=mul(cup,d,da)
s,sa=m.px('Cup/Light Effects/Shadow');c=burn(c,s,sa*.42)
l,la=m.px('Cup/Light Effects/Light');c=screen(c,l,la)
out=over(base,c,ca)
lid,lda=m.px('Lid/Lid');gm=m.mask('Lid');lda=lda*(gm if gm is not None else 1)
lum=lid.mean(2,keepdims=True)
c=np.broadcast_to(BROWN*1.25,lid.shape).copy()
s,sa=m.px('Lid/Light Effects/Shadow');c=burn(c,s,sa*.6)
l,la=m.px('Lid/Light Effects/Light');c=screen(c,l,la)
out=over(out,c,lda)
save(out,'window')
